    buf.writeln('ವಾಕ್ಪಾಣಿಪಾದಪಾಯೂಪಸ್ಥಕರಣರಸನಾ'
        'ಶ್ರೋತ್ರಚಕ್ಷುಃಸ್ತ್ವಙ್ಮನಃಸಂಪಾದೈಃ '
        'ಐಂದ್ರಿಯಕವ್ಯಾಪಾರೈಃ ಪ್ರತಿಫಲಿತಾನಾಂ '
        'ಜ್ಞಾನಾಜ್ಞಾನಸಂಭೂತಾನಾಂ ಸಮೇಷಾಮೇನಸಾಮಪನೋದನಾರ್ಥಂ ।');
    buf.writeln();

    // ══════════════════════════════════════════════════════════════
    // ❸ Identity
    // ══════════════════════════════════════════════════════════════
    buf.writeln('$gotra ಗೋತ್ರೋತ್ಪನ್ನಸ್ಯ ।');
    buf.writeln('$name ನಾಮಧೇಯಸ್ಯ ।');
    buf.writeln('ಮಮ ಉಪಾತ್ತ ಸಮಸ್ತ ದುರಿತಕ್ಷಯ ದ್ವಾರಾ ।');
    buf.writeln('ಶ್ರೀ ಪರಮೇಶ್ವರ ಪ್ರೀತ್ಯರ್ಥಂ ।');
    buf.writeln('ಮಮ ಸಕುಟುಂಬಸ್ಯ ಸಪರಿವಾರಸ್ಯ ।');
    buf.writeln();

    // ══════════════════════════════════════════════════════════════
    // ❹ ತಾಪತ್ರಯ ನಿವಾರಣ (Section 3)
    // ══════════════════════════════════════════════════════════════
    buf.writeln('ಆಧ್ಯಾತ್ಮಿಕ ಆದಿದೈವಿಕ ಆದಿಭೌತಿಕ '
        'ತಾಪತ್ರಯಾಣಾಂ ನಿವಾರಣಾರ್ಥಂ ।');
    buf.writeln('ಸಂಚಿತ ಪ್ರಾರಬ್ಧ ಆಗಾಮಿ ಪಾಪಘಟಿತಾನಾಂ '
        'ತಾಪತ್ರಯಾಣಾಂ ನಿವಾರಣಾರ್ಥಂ ।');

    // ❺ ಪಾಪಪರಿಹಾರ (Section 12)
    buf.writeln('ಇಹ ಜನ್ಮನಿ ಜನ್ಮಪ್ರಭೃತ್ಯೇತತ್ಕ್ಷಣಪರ್ಯಂತಂ '
        'ಬಾಲ್ಯೌಮಾರಯೌವನವಾರ್ಧಕ್ಯೇಷು '
        'ಜಾಗ್ರತ್ಸ್ವಪ್ನಸುಷುಪ್ತ್ಯವಸ್ಥಾಸು '
        'ಕಾಮಕ್ರೋಧಲೋಭಮೋಹಮದಮಾತ್ಸರ್ಯಾಜ್ಞೈಃ '
        'ಮನೋವ್ಯಾಪಾರೈಃ ವಚನಾದಾನವಿಹರಣೋತ್ಸರ್ಗಾನಂದಾಜ್ಞೈಃ '
        'ಕರ್ಮೇಂದ್ರಿಯವ್ಯಾಪಾರೈಶ್ಚ '
        'ಜ್ಞಾನೋಽಜ್ಞಾನತಶ್ಚ ಸ್ವತಃ ಪರಪ್ರೇರಣಯಾ ವಾ '
        'ಕೃತಾನಾಂ ಪಾಪಾನಾಂ ಪರಿಹಾರಾರ್ಥಂ ।');

    // ❻ ಬಾಧಾಪರಿಹಾರ (Section 13)
    buf.writeln('ಸಮಸ್ತ ಭೂತಪ್ರೇತಪಿಶಾಚಬಾಧಾ ಪರಿಹಾರಾರ್ಥಂ ।');

    // ❼ ಷಟ್ಕರ್ಮ ನಿವಾರಣ (Section 14)
    buf.writeln('ಉಚ್ಚಾಟನಸ್ತಂಭನಮೋಹನಾಕರ್ಷಣವಿದ್ವೇಷಣಮಾರಣಾತ್ಮಕ '
        'ಷಟ್ಕರ್ಮ ಪ್ರಯೋಗಜನಿತ ಪೀಡಾ ಶಾಂತ್ಯರ್ಥಂ ।');

    // ❽ ಭಯ ನಿರಸನ (Section 18)
    buf.writeln('ರಾಜಚೋರಶತ್ರುಶಸ್ತ್ರವಹ್ನಿವಾಯುವಾರಿ'
        'ಸರೀಸೃಪದುಷ್ಟಮೃಗಭಯ ನಿರಸನಾರ್ಥಂ ।');

    // ❾ ಗ್ರಹಚಾರ ಪರಿಹಾರ (Section 50)
    buf.writeln('ಜಾತಕಭಾವೇ ಗೋಚರೇ ವಾ ಅರಿಷ್ಟಸ್ಥಾನಸ್ಥಿತಾನಾಂ '
        'ಆದಿತ್ಯಾದೀನಾಂ ನವಾನಾಂ ಗ್ರಹಾಣಾಂ '
        'ಆನುಕೂಲ್ಯ ಸಿದ್ಧ್ಯರ್ಥಂ ।');
    buf.writeln('ಕಾಲಸರ್ಪ ದೋಷ ನಿವೃತ್ತ್ಯರ್ಥಂ ।');
    buf.writeln('ವಾಸ್ತು ದೋಷ ನಿವೃತ್ತ್ಯರ್ಥಂ ।');

    // ❿ ಉಪದ್ರವ ಪರಿಹಾರ (Section 25)
    buf.writeln('ಸಮಸ್ತ ಭೂತಪ್ರೇತಪಿಶಾಚಬ್ರಹ್ಮರಾಕ್ಷಸಯಕ್ಷ'
        'ಯಮದೂತಶಾಕಿನೀಡಾಕಿನೀ'
        'ಸರ್ಪಶ್ವಾಪದತಸ್ಕರಜ್ವರಾದ್ಯುಪದ್ರವಾಣಾಂ '
        'ಸಮೂಲಮುನ್ಮೂಲನಾರ್ಥಂ ।');

    // ⓫ ಮೃತ್ಯುಕಂಟಕ ನಿವಾರಣ (Section 30)
    buf.writeln('ಅಪಮೃತ್ಯು ಕಾಲಮೃತ್ಯು ವ್ಯಾಲಮೃತ್ಯು ಕ್ರೂರಮೃತ್ಯು '
        'ದುಷ್ಟಮೃತ್ಯು ಅರಿಷ್ಟಮೃತ್ಯು ಕ್ಷುದ್ರಮೃತ್ಯು '
        'ಸಪ್ತವಿಧ ಮೃತ್ಯುಕಂಟಕಾನಾಂ ಪರಿಹಾರಾರ್ಥಂ ।');

    // ⓬ ದಾರಿದ್ರ್ಯ ಪರಿಹಾರ (Section 4)
    buf.writeln('ಅನ್ನ ವಸ್ತ್ರ ನಿವಾಸ ಭೂಮಿ ಸಂತತಿ ಸಂಪತ್ತಿ '
        'ಆಪ್ತೇಷ್ಟ ಮಿತ್ರಪರಿವಾರ '
        'ಅಷ್ಟವಿಧ ದಾರಿದ್ರ್ಯಾಣಾಂ ಪರಿಹಾರಾರ್ಥಂ ।');

    // ⓭ ಪಿತೃತೃಪ್ತಿ (Section 56)
    buf.writeln('ಸಮಸ್ತ ಪಿತೃಣಾಂ ನಿರತಿಶಯ ಶಾಶ್ವತ ಪುಣ್ಯಲೋಕನಿವಾಸ '
        'ಅನಂತವಾಸ್ತಿಕ ತೃಪ್ತಿ ಪ್ರಾಪ್ತ್ಯರ್ಥಂ ।');

    buf.writeln('ಸಮಸ್ತ ಆಧಿ ವ್ಯಾಧಿ ಉಪಾಧಿ ಶಮನಾರ್ಥಂ ।');
    buf.writeln();

    // ══════════════════════════════════════════════════════════════
    // ⓮ ಅಭೀಷ್ಟ ಸಿದ್ಧಿ + ಮಂಗಲ ಕಾಮನಾ (Sections 6, 22, 24, 39, 48)
    // ══════════════════════════════════════════════════════════════
    buf.writeln('ಸರ್ವಾರಿಷ್ಟ ಶಾಂತಿ ನಿಮಿತ್ತಂ ।');
    // Ashtaishwarya (Section 6)
    buf.writeln('ಗೋಭೂಗೃಹಧನಧಾನ್ಯಕನಕವಸ್ತುವಾಹನೇತಿ '
        'ಅಷ್ಟವಿಧ ಸಂಪದಭಿವೃದ್ಧ್ಯರ್ಥಂ ।');
    buf.writeln('ಸಕಲಕ್ಷೇಮಸ್ಥೈರ್ಯವಿಜಯಶುಭಾಭಯ '
        'ಆಯುಶ್ಚ ಆನಂದ ಆರೋಗ್ಯ ಐಶ್ವರ್ಯಾಭಿವೃದ್ಧ್ಯರ್ಥಂ ।');
    // Abhishta Siddhi (Section 24)
    buf.writeln('ದೀರ್ಘಾಯುವಿಪುಲಧನಧಾನ್ಯಪುತ್ರಪೌತ್ರಾದ್ಯವಿಚ್ಛಿನ್ನ'
        'ಸಂತತಿವೃದ್ಧಿಸ್ಥಿರಲಕ್ಷ್ಮೀಕೀರ್ತಿಲಾಭ'
        'ಶತ್ರುಪರಾಜಯಾದ್ಯಭೀಷ್ಟಫಲಸಿದ್ಧ್ಯರ್ಥಂ ।');
    // Chaturvidha Purushartha
    buf.writeln('ಧರ್ಮ ಅರ್ಥ ಕಾಮ ಮೋಕ್ಷ '
        'ಚತುರ್ವಿಧ ಫಲ ಪುರುಷಾರ್ಥ ಸಿದ್ಧ್ಯರ್ಥಂ ।');
    buf.writeln('ಸಮಸ್ತ ಸನ್ಮಂಗಳಾವಾಪ್ತ್ಯರ್ಥಂ ।');
    buf.writeln();

    // ══════════════════════════════════════════════════════════════
    // ⓯ ವಿಶೇಷ ಸಂಕಲ್ಪ — Specific karya
    // ══════════════════════════════════════════════════════════════
    if (visheshaSankalpa != null && visheshaSankalpa.isNotEmpty) {
      final karya = visheshaSankalpas[visheshaSankalpa] ?? visheshaSankalpa;
      buf.writeln(karya);
    } else {
      buf.writeln('ಇಷ್ಟ ದೇವತಾ ಪ್ರೀತ್ಯರ್ಥಂ ಪೂಜಾಂ ಕರಿಷ್ಯೇ ॥');
    }

    return buf.toString().trim();
  }

  /// Get list of all Vishesha Sankalpa karya names
  static List<String> get karyaNames => visheshaSankalpas.keys.toList();
